-- SIKRS Profesional: skema PostgreSQL berdasarkan ERD sistem krs.pgerd
-- Jalankan pada database BARU/target yang benar. Tidak menghapus tabel atau data yang ada.
CREATE TABLE IF NOT EXISTS prodi (
  kode_prodi VARCHAR(10) PRIMARY KEY,
  nama_prodi VARCHAR(100) NOT NULL,
  jenjang VARCHAR(3) NOT NULL CHECK (jenjang IN ('D3','D4','S1','S2','S3'))
);
CREATE TABLE IF NOT EXISTS dosen (
  id_dosen INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nidn VARCHAR(10) NOT NULL UNIQUE,
  nama VARCHAR(100) NOT NULL,
  email VARCHAR(100),
  kode_prodi VARCHAR(10) NOT NULL REFERENCES prodi(kode_prodi) ON UPDATE CASCADE ON DELETE RESTRICT
);
CREATE TABLE IF NOT EXISTS mahasiswa (
  nim VARCHAR(12) PRIMARY KEY,
  nama VARCHAR(100) NOT NULL,
  email VARCHAR(100),
  tahun_masuk SMALLINT NOT NULL,
  status VARCHAR(10) NOT NULL CHECK (status IN ('aktif','cuti','lulus','keluar')),
  kode_prodi VARCHAR(10) NOT NULL REFERENCES prodi(kode_prodi) ON UPDATE CASCADE ON DELETE RESTRICT,
  id_dosen_pa INTEGER REFERENCES dosen(id_dosen) ON UPDATE CASCADE ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  no_hp VARCHAR(20)
);
CREATE TABLE IF NOT EXISTS mata_kuliah (
  kode_mk VARCHAR(10) PRIMARY KEY,
  nama_mk VARCHAR(100) NOT NULL,
  sks SMALLINT NOT NULL CHECK (sks BETWEEN 1 AND 6),
  semester_ke SMALLINT NOT NULL CHECK (semester_ke BETWEEN 1 AND 14)
);
CREATE TABLE IF NOT EXISTS periode (
  id_periode VARCHAR(5) PRIMARY KEY,
  nama_periode VARCHAR(30) NOT NULL,
  tgl_mulai DATE NOT NULL,
  tgl_selesai DATE NOT NULL,
  CHECK (tgl_selesai >= tgl_mulai)
);
CREATE TABLE IF NOT EXISTS kelas (
  id_kelas INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kode_mk VARCHAR(10) NOT NULL REFERENCES mata_kuliah(kode_mk) ON UPDATE CASCADE ON DELETE RESTRICT,
  id_periode VARCHAR(5) NOT NULL REFERENCES periode(id_periode) ON UPDATE CASCADE ON DELETE RESTRICT,
  id_dosen INTEGER NOT NULL REFERENCES dosen(id_dosen) ON UPDATE CASCADE ON DELETE RESTRICT,
  nama_kelas VARCHAR(5) NOT NULL,
  kuota SMALLINT NOT NULL CHECK (kuota > 0),
  UNIQUE (kode_mk, id_periode, nama_kelas)
);
CREATE TABLE IF NOT EXISTS krs (
  id_krs INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nim VARCHAR(12) NOT NULL REFERENCES mahasiswa(nim) ON UPDATE CASCADE ON DELETE RESTRICT,
  id_periode VARCHAR(5) NOT NULL REFERENCES periode(id_periode) ON UPDATE CASCADE ON DELETE RESTRICT,
  tgl_isi DATE NOT NULL DEFAULT CURRENT_DATE,
  status VARCHAR(10) NOT NULL CHECK (status IN ('draft','diajukan','disetujui','ditolak')),
  UNIQUE (nim, id_periode)
);
CREATE TABLE IF NOT EXISTS krs_detail (
  id_krs INTEGER NOT NULL REFERENCES krs(id_krs) ON UPDATE CASCADE ON DELETE CASCADE,
  id_kelas INTEGER NOT NULL REFERENCES kelas(id_kelas) ON UPDATE CASCADE ON DELETE RESTRICT,
  nilai_huruf VARCHAR(2),
  PRIMARY KEY (id_krs, id_kelas),
  CHECK (nilai_huruf IS NULL OR nilai_huruf IN ('A','A-','B+','B','B-','C+','C','D','E'))
);
CREATE TABLE IF NOT EXISTS aturan_akademik (
  kode VARCHAR(30) PRIMARY KEY,
  nilai INTEGER NOT NULL,
  keterangan VARCHAR(200)
);
CREATE INDEX IF NOT EXISTS idx_mahasiswa_prodi ON mahasiswa(kode_prodi);
CREATE INDEX IF NOT EXISTS idx_kelas_periode ON kelas(id_periode);
CREATE INDEX IF NOT EXISTS idx_krs_periode ON krs(id_periode);
